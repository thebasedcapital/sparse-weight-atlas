"""Export a readable, runnable-as-documentation model.py listing every nonzero MLP weight.

Usage:
    PYTHONPATH=engine python -m swa.export_modelpy --model csp_yolo1
    PYTHONPATH=engine python -m swa.export_modelpy --model csp_yolo1 \
        --scores-dir runs/csp_yolo1/scores_pilot --out site/pilot/pilot
    PYTHONPATH=engine python -m swa.export_modelpy --model csp_yolo1 \
        --scores-dirs runs/csp_yolo1/scores_casestudy runs/csp_yolo1/scores_pilot

Writes <out>/<model>/model.py: a summary header with counts, then for each layer and
each MLP matrix, every nonzero weight as one entry with its value and — when the weight
was scored — its predicate source and one-line description inline.
"""
import argparse
from pathlib import Path

import numpy as np

from .export_site import (MATRIX_NAMES, PAPER_ROBUST_RATE, ROBUST_COUNT_FIELDS,
                          STATUSES, VERDICT_STATUSES, CandidateIndex, ProfileIndex,
                          interp_rate, load_scores, robust_rates, robust_rules,
                          score_directories, score_provenance)



def repo_root() -> Path:
    return Path(__file__).resolve().parents[2]


def pystr(s: str) -> str:
    """A Python string literal (repr) — always valid Python source."""
    return repr(s)


def export_modelpy(model: str, runs: Path, out: Path,
                   scores_dir: Path | None = None,
                   scores_dirs: list[Path] | None = None) -> dict:
    runs_dir = runs / model
    out_dir = out / model
    out_dir.mkdir(parents=True, exist_ok=True)

    npz = np.load(runs_dir / "weights.npz")
    layer, matrix, row, col, value = (npz["layer"], npz["matrix"], npz["row"],
                                      npz["col"], npz["value"])
    W = len(layer)

    directories = score_directories(runs_dir, scores_dir, scores_dirs)
    scores = load_scores(runs_dir, scores_dirs=directories)
    provenance = score_provenance(directories)
    profiles = ProfileIndex(runs_dir)
    candidates = CandidateIndex(runs_dir)
    counts = {"total": W, **{status: 0 for status in STATUSES},
              **{field: 0 for field in ROBUST_COUNT_FIELDS.values()}}
    a_recs, b_recs = [], []
    for wid in range(W):
        record = scores.get(wid) or {}
        status = record.get("status")
        if status is None:
            status = "candidate" if candidates.best(profiles.shard_of(wid), wid) else "unscored"
        counts[status] += 1
        for field, passed in robust_rules(record).items():
            counts[ROBUST_COUNT_FIELDS[field]] += passed
        if record.get("A"):
            a_recs.append(record["A"])
        if record.get("B"):
            b_recs.append(record["B"])
    counts["verdicts"] = sum(counts[status] for status in VERDICT_STATUSES)
    rates = {
        **robust_rates(counts, counts["verdicts"]),
        "interpA": interp_rate(a_recs, counts["verdicts"]),
        "interpB": interp_rate(b_recs, counts["verdicts"]),
    }
    n_layers = int(layer.max()) + 1 if W else 0

    lines = []
    ap = lines.append
    ap('"""Auto-generated by swa.export_modelpy — DO NOT EDIT.')
    ap('')
    ap(f'Documentation of every nonzero MLP weight of {model}.')
    ap('Rule counts and rates describe only the merged score verdicts, not all model weights.')
    ap('These sources may include selected case studies and are not necessarily a uniform sample.')
    ap('Use the separate pure uniform-pilot report for headline paper comparisons.')
    ap('All reported rule rates use VERDICTS = SCORED + NOISE_FLOOR + NO_CANDIDATE.')
    ap('Cone: mean >= 0.75 and mean - 2*SEM > 0.')
    ap('Beats-null-mean: cone, and mean - 2*SEM > null_mean.')
    ap('Strict: cone, and the stored robust.pass verdict (lower > null_mean + 2*null_sd).')
    ap('')
    ap('W[layer][matrix] is a list of entries, one per nonzero weight, in wid order:')
    ap('    (wid, row, col, value, predicate_source_or_None, description_or_None, status)')
    ap('matrix 0 = c_fc [out=d_mlp, in=d_model], matrix 1 = c_proj [out=d_model, in=d_mlp].')
    ap('Predicate source is the executable Python predicate f(tokens, pos) for when the weight')
    ap('matters. status: "robust" = passed the held-out cone test; "scored" = exactly scored,')
    ap('not robust; "candidate" = UNVERIFIED rule from the synthesizer (search proxy only, never')
    ap('tested on held-out text); "noise_floor" / "unscored" = no predicate.')
    ap('"""')
    ap('')
    ap(f'MODEL = {pystr(model)}')
    ap(f'TOTAL_WEIGHTS = {W}')
    ap(f'PROVENANCE = {provenance!r}')
    ap(f'COUNTS = {counts!r}')
    ap(f'RATES = {rates!r}')
    ap(f'SCORED = {counts["scored"]}')
    ap(f'NOISE_FLOOR = {counts["noise_floor"]}')
    ap(f'NO_CANDIDATE = {counts["no_candidate"]}')
    ap(f'CANDIDATE = {counts["candidate"]}  # unverified synthesized rules')
    ap(f'UNSCORED = {counts["unscored"]}')
    ap(f'VERDICTS = {counts["verdicts"]}  # denominator for every rule rate below')
    ap(f'ROBUSTLY_INTERPRETABLE = {counts["robust_pass"]}  # cone rule')
    ap(f'ROBUST_BEATS_NULL_MEAN = {counts["robust_beats_null_mean"]}')
    ap(f'ROBUST_STRICT = {counts["robust_strict"]}')
    ap(f'PAPER_ROBUST_RATE = {PAPER_ROBUST_RATE!r}  # context only; merged sources are not a uniform pilot')
    ap(f'OUR_ROBUST_RATE = {rates["robust"]!r}  # cone / VERDICTS, not / TOTAL_WEIGHTS')
    ap(f'OUR_ROBUST_BEATS_NULL_MEAN_RATE = {rates["robust_beats_null_mean"]!r}')
    ap(f'OUR_ROBUST_STRICT_RATE = {rates["robust_strict"]!r}')
    ap('')
    ap('W = [')

    wid = 0
    for L in range(n_layers):
        ap(f'    # ---- layer {L} ----')
        ap('    [')
        for m in (0, 1):
            n_here = int(((layer == L) & (matrix == m)).sum())
            ap(f'        # {MATRIX_NAMES[m]} ({n_here} nonzero weights)')
            while wid < W and layer[wid] == L and matrix[wid] == m:
                rec = scores.get(wid)
                base = f'({wid}, {int(row[wid])}, {int(col[wid])}, {float(value[wid])!r}, '
                if rec is not None and rec.get("status") == "scored":
                    tag = "robust" if robust_rules(rec)["pass"] else "scored"
                    py, desc = rec.get("py"), rec.get("desc")
                elif rec is None and (cand := candidates.best(profiles.shard_of(wid), wid)):
                    tag, py, desc = "candidate", cand.get("py"), cand.get("desc")
                else:
                    tag = (rec or {}).get("status", "unscored")
                    py = desc = None
                if py is None:
                    entry = base + f'None, None, {pystr(tag)}),'
                else:
                    entry = base + f'{pystr(py)}, {pystr(desc or "")}, {pystr(tag)}),'
                ap('        ' + entry)
                wid += 1
        ap('    ],')
    ap(']')

    out_path = out_dir / "model.py"
    out_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return {"model": model, "total": W, "scored": counts["scored"],
            "robust": counts["robust_pass"], "counts": counts, "rates": rates,
            "provenance": provenance, "path": str(out_path), "bytes": out_path.stat().st_size}


def main():
    root = repo_root()
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--model", default="csp_yolo1")
    ap.add_argument("--root", default=str(root))
    ap.add_argument("--runs", default=None)
    ap.add_argument("--out", default=None)
    score_args = ap.add_mutually_exclusive_group()
    score_args.add_argument("--scores-dir", default=None,
                            help="one directory of score JSONL shards (default: <runs>/<model>/scores)")
    score_args.add_argument("--scores-dirs", nargs="+", default=None,
                            help="score directories to merge in order; later directories win")
    args = ap.parse_args()

    runs = Path(args.runs) if args.runs else Path(args.root) / "runs"
    out = Path(args.out) if args.out else Path(args.root) / "site" / "data"
    res = export_modelpy(args.model, runs, out,
                         scores_dir=Path(args.scores_dir) if args.scores_dir else None,
                         scores_dirs=[Path(directory) for directory in args.scores_dirs]
                         if args.scores_dirs else None)
    c = res["counts"]
    print(f"[export_modelpy] {res['model']}: total={c['total']} scored={c['scored']} "
          f"verdicts={c['verdicts']} robust_pass={c['robust_pass']} "
          f"robust_beats_null_mean={c['robust_beats_null_mean']} robust_strict={c['robust_strict']} "
          f"-> {res['path']} ({res['bytes']} bytes)")


if __name__ == "__main__":
    main()
