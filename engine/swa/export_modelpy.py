"""Export a readable, runnable-as-documentation model.py listing every nonzero MLP weight.

Usage:
    PYTHONPATH=engine python -m swa.export_modelpy --model csp_yolo1
    PYTHONPATH=engine python -m swa.export_modelpy --model csp_yolo1 \
        --scores-dir runs/csp_yolo1/scores_pilot --out site/pilot/pilot

Writes <out>/<model>/model.py: a summary header with counts, then for each layer and
each MLP matrix, every nonzero weight as one entry with its value and — when the weight
was scored — its predicate source and one-line description inline.
"""
import argparse
import json
from pathlib import Path

import numpy as np

MATRIX_NAMES = ("c_fc", "c_proj")


def repo_root() -> Path:
    return Path(__file__).resolve().parents[2]


def pystr(s: str) -> str:
    """A Python string literal (repr) — always valid Python source."""
    return repr(s)


def export_modelpy(model: str, runs: Path, out: Path,
                   scores_dir: Path | None = None) -> dict:
    runs_dir = runs / model
    out_dir = out / model
    out_dir.mkdir(parents=True, exist_ok=True)

    npz = np.load(runs_dir / "weights.npz")
    layer, matrix, row, col, value = (npz["layer"], npz["matrix"], npz["row"],
                                      npz["col"], npz["value"])
    W = len(layer)

    scores = {}
    sdir = scores_dir if scores_dir is not None else runs_dir / "scores"
    if sdir.is_dir():
        for path in sorted(sdir.glob("*.jsonl")):
            with open(path, "r", encoding="utf-8") as f:
                for line in f:
                    line = line.strip()
                    if line:
                        rec = json.loads(line)
                        scores[int(rec["wid"])] = rec

    n_layers = int(layer.max()) + 1 if W else 0
    scored = sum(1 for r in scores.values() if r.get("status") == "scored")
    robust = sum(1 for r in scores.values()
                 if r.get("robust") and r["robust"].get("pass"))

    lines = []
    ap = lines.append
    ap('"""Auto-generated by swa.export_modelpy — DO NOT EDIT.')
    ap('')
    ap(f'Documentation of every nonzero MLP weight of {model}.')
    ap('')
    ap('W[layer][matrix] is a list of entries, one per nonzero weight, in wid order:')
    ap('    (wid, row, col, value, predicate_source_or_None, description_or_None)')
    ap('matrix 0 = c_fc [out=d_mlp, in=d_model], matrix 1 = c_proj [out=d_model, in=d_mlp].')
    ap('Predicate source is the executable Python predicate f(tokens, pos) found by the')
    ap('pipeline; description is its one-line gloss. None = not scored / no candidate.')
    ap('"""')
    ap('')
    ap(f'MODEL = {pystr(model)}')
    ap(f'TOTAL_WEIGHTS = {W}')
    ap(f'SCORED = {scored}')
    ap(f'ROBUSTLY_INTERPRETABLE = {robust}')
    ap(f'PAPER_ROBUST_RATE = {0.15!r}  # Gao et al. 2025, Table 1 (arXiv 2607.02964)')
    ap(f'OUR_ROBUST_RATE = {robust / W!r}' if W else 'OUR_ROBUST_RATE = None')
    ap('')
    ap('W = [')

    wid = 0
    for L in range(n_layers):
        ap(f'    # ---- layer {L} ----')
        ap('    [')
        for m in (0, 1):
            n_here = int(((layer == L) & (matrix == m)).sum())
            ap(f'        # {MATRIX_NAMES[m]} ({n_here} nonzero weights)')
            while wid < W and layer[wid] == L and matrix[wid] == m:
                rec = scores.get(wid)
                if rec is None or rec.get("status") != "scored":
                    entry = (f'({wid}, {int(row[wid])}, {int(col[wid])}, {float(value[wid])!r}, '
                             f'None, None),')
                else:
                    entry = (f'({wid}, {int(row[wid])}, {int(col[wid])}, {float(value[wid])!r}, '
                             f'{pystr(rec.get("py") or "")}, {pystr(rec.get("desc") or "")}),')
                ap('        ' + entry)
                wid += 1
        ap('    ],')
    ap(']')

    out_path = out_dir / "model.py"
    out_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return {"model": model, "total": W, "scored": scored, "robust": robust,
            "path": str(out_path), "bytes": out_path.stat().st_size}


def main():
    root = repo_root()
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--model", default="csp_yolo1")
    ap.add_argument("--root", default=str(root))
    ap.add_argument("--runs", default=None)
    ap.add_argument("--out", default=None)
    ap.add_argument("--scores-dir", default=None,
                    help="directory of <shard>.jsonl score records "
                         "(default: <runs>/<model>/scores), e.g. runs/<model>/scores_pilot")
    args = ap.parse_args()

    runs = Path(args.runs) if args.runs else Path(args.root) / "runs"
    out = Path(args.out) if args.out else Path(args.root) / "site" / "data"
    res = export_modelpy(args.model, runs, out,
                         scores_dir=Path(args.scores_dir) if args.scores_dir else None)
    print(f"[export_modelpy] {res['model']}: total={res['total']} scored={res['scored']} "
          f"robust={res['robust']} -> {res['path']} ({res['bytes']} bytes)")


if __name__ == "__main__":
    main()
